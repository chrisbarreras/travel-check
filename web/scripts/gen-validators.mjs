// Compiles standalone validators from the generated showcase JSON Schema (research R3).
// The schema is generated from the pipeline's Pydantic models (ADR-0007), so the browser
// checks loaded data against the one data contract without shipping the Ajv compiler.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const schemaPath = fileURLToPath(
  new URL("../../shared/schemas/showcase.schema.json", import.meta.url),
);
const outDir = fileURLToPath(new URL("../src/data/generated/", import.meta.url));

/** Contract types the page loads, with the name of the exported validator. */
const TARGETS = {
  validateShowcaseIndex: "ShowcaseIndex",
  validateRouteFile: "RouteFile",
  validateShowcaseManifest: "ShowcaseManifest",
};

let schema;
try {
  schema = JSON.parse(readFileSync(schemaPath, "utf8"));
} catch (error) {
  console.error(`gen-validators: cannot read ${schemaPath}: ${String(error)}`);
  process.exit(1);
}
for (const name of Object.values(TARGETS)) {
  if (!schema.$defs?.[name]) {
    console.error(`gen-validators: the schema has no $defs.${name}`);
    process.exit(1);
  }
}

const ajv = new Ajv2020({
  strict: true,
  allErrors: false,
  code: { source: true, esm: true, lines: false, optimize: true },
});
// Dates in the contract are ISO calendar dates (Pydantic `date`).
ajv.addFormat("date", /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/);
ajv.addSchema(schema, "showcase");

const refs = Object.fromEntries(
  Object.entries(TARGETS).map(([fn, name]) => [fn, `showcase#/$defs/${name}`]),
);
// Ajv's standalone output loads its string-length helper with `require`, which an ES module
// in the browser cannot do. The helper counts Unicode code points; inline the same rule.
const UCS2 = 'require("ajv/dist/runtime/ucs2length").default';
const code = standaloneCode(ajv, refs).replaceAll(UCS2, "((s) => [...s].length)");
if (code.includes("require(")) {
  console.error("gen-validators: generated code still uses require(); update the inlining");
  process.exit(1);
}

const header =
  "// Generated by scripts/gen-validators.mjs from shared/schemas/showcase.schema.json. Do not edit.\n";
mkdirSync(outDir, { recursive: true });
writeFileSync(`${outDir}validators.js`, header + code);

const dts =
  header +
  'import type { ErrorObject } from "ajv";\n\n' +
  "export interface Validator {\n" +
  "  (data: unknown): boolean;\n" +
  "  errors?: ErrorObject[] | null;\n" +
  "}\n\n" +
  Object.keys(TARGETS)
    .map((fn) => `export declare const ${fn}: Validator;\n`)
    .join("");
writeFileSync(`${outDir}validators.d.ts`, dts);
console.log(`gen-validators: wrote ${Object.keys(TARGETS).join(", ")}`);
